"""JSON with `//` and `/* */` comments and trailing commas.

Cursor's `permissions.json` and Devin CLI's configuration files are documented
as accepting both. A plain `json.loads` raises on a documented-valid file, so
comments and trailing commas are stripped in two string-aware passes (never
touching either inside a JSON string literal) before the text reaches
`json.loads`. Anything else that is not JSON still raises `ValueError`.
"""

from __future__ import annotations

import json
from pathlib import Path


def loads(text: str) -> object:
    return json.loads(_strip_trailing_commas(_strip_comments(text)))


def load_path(path: Path) -> object:
    """Read and parse `path`. `OSError`, `UnicodeDecodeError` and `ValueError`
    propagate, so a caller decides whether an unreadable file is a gap."""
    return loads(path.read_text(encoding="utf-8"))


def _strip_comments(text: str) -> str:
    out: list[str] = []
    i = 0
    n = len(text)
    in_string = False
    escape = False
    while i < n:
        ch = text[i]
        if in_string:
            out.append(ch)
            if escape:
                escape = False
            elif ch == "\\":
                escape = True
            elif ch == '"':
                in_string = False
            i += 1
            continue
        if ch == '"':
            in_string = True
            out.append(ch)
            i += 1
            continue
        if ch == "/" and i + 1 < n and text[i + 1] == "/":
            i += 2
            while i < n and text[i] not in "\r\n":
                i += 1
            continue
        if ch == "/" and i + 1 < n and text[i + 1] == "*":
            i += 2
            while i + 1 < n and not (text[i] == "*" and text[i + 1] == "/"):
                i += 1
            i += 2
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def _strip_trailing_commas(text: str) -> str:
    out: list[str] = []
    i = 0
    n = len(text)
    in_string = False
    escape = False
    while i < n:
        ch = text[i]
        if in_string:
            out.append(ch)
            if escape:
                escape = False
            elif ch == "\\":
                escape = True
            elif ch == '"':
                in_string = False
            i += 1
            continue
        if ch == '"':
            in_string = True
            out.append(ch)
            i += 1
            continue
        if ch == ",":
            j = i + 1
            while j < n and text[j] in " \t\r\n":
                j += 1
            if j < n and text[j] in "}]":
                i += 1
                continue
        out.append(ch)
        i += 1
    return "".join(out)
